/**
 * Intelligent LocalStorage sync:
 * - Purges old laptop/electronics cache
 * - Merges new products added via Telegram Bot or code dynamically
 */
export function getLocalCollection(key, fallback) {
  try {
    // 1. Purge all obsolete storage keys from previous builds
    const obsoleteKeys = [
      'nsb_products_v9_realprices',
      'nsb_products_v8_realprices',
      'nsb_products_v7_realprices',
      'nsb_products_v6_sport',
      'nsb_products_v5_sport',
      'nsb_products_v4_sport',
      'nsb_products_v3_sport',
      'nsb_products_v2_sport',
      'nsb_products_v1_sport',
      'nsb_products_sport',
      'nsb_products',
      'products',
      'nsb_categories_v3_sport',
      'nsb_banners_v3_sport'
    ];
    for (const oldKey of obsoleteKeys) {
      if (oldKey !== key) {
        try { localStorage.removeItem(oldKey); } catch (_) {}
      }
    }

    // If fallback is empty (user wiped products to add fresh via bot), reset immediately
    if (key.includes('products') && (!fallback || fallback.length === 0)) {
      try { localStorage.removeItem(key); } catch (_) {}
      return [];
    }

    const raw = localStorage.getItem(key);
    if (!raw) {
      localStorage.setItem(key, JSON.stringify(fallback));
      return fallback;
    }
    const parsed = JSON.parse(raw);

    // If cached collection contains obsolete laptops, electronics, or old generic "Yangi Mahsulot" cards, purge immediately
    if (key.includes('products') && Array.isArray(parsed)) {
      const hasOldLaptops = parsed.some(p => p.slug && (
        p.slug.includes('macbook') || 
        p.slug.includes('dell-optiplex') || 
        p.slug.includes('canon') ||
        p.slug.includes('apple') ||
        p.category === 'Kompyuter Texnikasi'
      ));

      // Check if duplicate placeholder cards exist (e.g. 4x "Yangi Mahsulot" cards)
      const hasPlaceholderDuplicates = parsed.some(p =>
        (p.title && (p.title.trim().toLowerCase() === 'yangi mahsulot' || p.title.trim().toLowerCase() === 'yangi sport mahsuloti')) ||
        (p.slug && p.slug.startsWith('yangi-mahsulot')) ||
        (p.slug && p.slug.includes('tatami') && p.slug !== 'professional-tatami-1x1m')
      );

      // Check if products have old incorrect 750,000 price
      const hasWrong750kPrices = parsed.some(p => p.price === 750000 && p.title && (
        p.title.includes('130000') || p.title.includes('339000') || p.title.includes('330000') || p.title.includes('169000') || p.title.includes('Charx') || p.title.includes('Chax')
      ));

      if (hasOldLaptops || hasPlaceholderDuplicates || hasWrong750kPrices) {
        console.log('⚡ Purging old cache / wrong prices from localStorage');
        localStorage.setItem(key, JSON.stringify(fallback));
        return fallback;
      }

      // Filter out any unwanted duplicates
      const cleanParsed = parsed.filter(p =>
        p && p.title &&
        p.title.trim().toLowerCase() !== 'yangi mahsulot' &&
        p.title.trim().toLowerCase() !== 'yangi sport mahsuloti' &&
        !(p.slug && p.slug.startsWith('yangi-mahsulot')) &&
        !(p.slug && p.slug.includes('tatami') && p.slug !== 'professional-tatami-1x1m')
      );

      // Auto-merge any new items in fallback (e.g., added from Telegram bot or updates)
      const existingIds = new Set(cleanParsed.map(p => p.id || p._id || p.slug));
      let hasNew = false;
      for (const item of fallback) {
        const id = item.id || item._id || item.slug;
        if (!existingIds.has(id)) {
          cleanParsed.unshift(item);
          existingIds.add(id);
          hasNew = true;
        }
      }
      if (hasNew || cleanParsed.length !== parsed.length) {
        localStorage.setItem(key, JSON.stringify(cleanParsed));
      }
      return cleanParsed;
    }

    if (key.includes('categories') && Array.isArray(parsed)) {
      const hasOldCats = parsed.some(c => c.slug === 'apple' || c.slug === 'orgtehnika');
      if (hasOldCats) {
        console.log('⚡ Purging old categories cache from localStorage');
        localStorage.setItem(key, JSON.stringify(fallback));
        return fallback;
      }
    }

    if (key.includes('orders') && Array.isArray(parsed)) {
      const hasOldOrders = parsed.some(o => 
        o.items?.some(it => {
          const t = (it.title || '').toLowerCase();
          return t.includes('macbook') || t.includes('optiplex') || t.includes('canon') || t.includes('apple');
        })
      );
      if (hasOldOrders || parsed.length === 0) {
        console.log('⚡ Purging old orders cache from localStorage in favor of Sport orders');
        localStorage.setItem(key, JSON.stringify(fallback));
        return fallback;
      }
    }

    return parsed;
  } catch (e) {
    console.warn('LocalStorage access warning:', e);
    return fallback;
  }
}

export function saveLocalCollection(key, data) {
  try {
    localStorage.setItem(key, JSON.stringify(data));
  } catch (e) {
    console.warn('LocalStorage save error:', e);
  }
}
